clear, clc;

n = 1000; % problem dimension
[obj, grad, hess] = extended_rosenbrock_function(n,100); % load objective function, gradient and Hessian
x0 = repmat([-1.2; 1],n/2,1); % starting point

%--------------------------------------------------------------------------

% run the gradient method
[x,f,alg_info] = gradient_method(obj,grad,x0);

% print final statistics
fprintf(['\n********************** FINAL RESULTS **********************' ...
         '\nAlgorithm: Gradient Method' ...
         '\nf =  %-.4e'   ...
         '\niterations = %-i' ...
         '\nsup-norm of g = %.4e'   ...
         '\nflag = %-i' ...
         '\n***********************************************************\n\n'], ...
         f,alg_info.it,alg_info.sup_norm_g,alg_info.flag);

% figure;
% semilogy(alg_info.f_vec,'r');

keyboard;

%--------------------------------------------------------------------------

% run the Newton method
[x,f,alg_info] = newton_method(obj,grad,hess,x0);

% print final statistics
fprintf(['\n********************** FINAL RESULTS **********************' ...
         '\nAlgorithm: Newton Method' ...
         '\nf =  %-.4e'   ...
         '\niterations = %-i' ...
         '\nsup-norm of g = %.4e'   ...
         '\nflag = %-i' ...
         '\n***********************************************************\n\n'], ...
         f,alg_info.it,alg_info.sup_norm_g,alg_info.flag);

% hold on;
% semilogy(alg_info.f_vec,'b');

keyboard;

%--------------------------------------------------------------------------

% run the spectral gradient method
[x,f,alg_info] = spectral_gradient_method(obj,grad,x0);

% print final statistics
fprintf(['\n********************** FINAL RESULTS **********************' ...
         '\nAlgorithm: Spectral Gradient Method' ...
         '\nf =  %-.4e'   ...
         '\niterations = %-i' ...
         '\nsup-norm of g = %.4e'   ...
         '\nflag = %-i' ...
         '\n***********************************************************\n\n'], ...
         f,alg_info.it,alg_info.sup_norm_g,alg_info.flag);

% hold on;
% semilogy(alg_info.f_vec,'g');

keyboard;

%--------------------------------------------------------------------------